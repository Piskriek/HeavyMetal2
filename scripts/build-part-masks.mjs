/**
 * Tint masks for the painted goblin parts (plan §9.6).
 *
 * The parts are painted in fixed "channel" colours on purpose: skin in the toxic-green family,
 * leather dark brown, metal brass, accents neutral red. This script finds each channel by hue band
 * in every keyed part and writes one greyscale mask per channel that covers enough of the part
 * (white = that channel, at half resolution; the compositor stretches it over the part). The
 * compositor then paints the player's swatch colour through the mask with `mix-blend-mode: color`,
 * which keeps the painted light and shade and swaps only hue and saturation.
 *
 * Usage: node scripts/build-part-masks.mjs   (after key-art.ts; safe to re-run, output is deterministic)
 * Writes public/avatar-parts/masks/<id>-<channel>.png and src/game/meta/painted-masks.generated.ts.
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePng, encodePng } from './edge-magenta-lib.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const keyedDir = join(root, 'public/avatar-parts/keyed');
const maskDir = join(root, 'public/avatar-parts/masks');
const manifest = join(root, 'src/game/meta/painted-masks.generated.ts');
/** A channel needs at least this share of the part's opaque pixels to get a mask. */
const MIN_COVERAGE = 0.015;

function hsv(r, g, b) {
  const max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min;
  let h = 0;
  if (d) {
    if (max === r) h = ((g - b) / d) % 6;
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
    if (h < 0) h += 360;
  }
  return [h, max ? d / max : 0, max / 255];
}

/** Which channel a painted pixel belongs to (or null). The bands follow the batch palette rules. */
export function channelOf(r, g, b) {
  const [h, s, v] = hsv(r, g, b);
  if (h >= 65 && h <= 125 && s >= 0.25 && v >= 0.18) return 'skin';
  if ((h >= 345 || h <= 12) && s >= 0.45 && v >= 0.3) return 'accent';
  // Brass: saturated and bright (ivory teeth and pale highlights are too grey to count).
  if (h >= 30 && h <= 52 && s >= 0.5 && v >= 0.5) return 'metal';
  // Leather: a real brown, not the near-black outline.
  if (h >= 12 && h <= 40 && s >= 0.4 && v >= 0.2 && v < 0.5) return 'leather';
  return null;
}

const CHANNELS = ['skin', 'leather', 'metal', 'accent'];
/** What each layer is allowed to re-tint (eyes are yellow, not brass; hair is painted in the accent red). */
const ALLOWED = {
  head: ['skin'], eyes: ['skin'], ears: ['skin'], nose: ['skin', 'metal'], mouth: ['skin', 'metal'],
  hair: ['accent'], eyewear: ['leather', 'metal'], headgear: ['leather', 'metal', 'accent'], neck: ['leather', 'metal', 'accent'], warpaint: [],
};
mkdirSync(maskDir, { recursive: true });
const out = {};
for (const file of existsSync(keyedDir) ? readdirSync(keyedDir).sort() : []) {
  if (!file.endsWith('.png') || file.startsWith('background-')) continue;
  const id = file.slice(0, -4);
  const allowed = ALLOWED[id.split('-')[0]] ?? CHANNELS;
  const { w, h, data } = decodePng(join(keyedDir, file));
  const hw = Math.ceil(w / 2), hh = Math.ceil(h / 2);
  const masks = Object.fromEntries(CHANNELS.map((c) => [c, new Float32Array(hw * hh)]));
  const count = Object.fromEntries(CHANNELS.map((c) => [c, 0]));
  let opaque = 0;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const i = (y * w + x) * 4;
    const a = data[i + 3];
    if (a < 8) continue;
    opaque++;
    const c = channelOf(data[i], data[i + 1], data[i + 2]);
    if (!c) continue;
    count[c]++;
    masks[c][(y >> 1) * hw + (x >> 1)] += a / 4; // 2×2 box average of alpha-weighted membership
  }
  const channels = [];
  for (const c of CHANNELS) {
    // Brass must be a real part of the piece (6 %), not a few warm highlights.
    if (!allowed.includes(c) || !opaque || count[c] / opaque < (c === 'metal' ? 0.06 : MIN_COVERAGE)) continue;
    const px = Buffer.alloc(hw * hh * 4);
    for (let j = 0; j < hw * hh; j++) {
      const v = Math.min(255, Math.round(masks[c][j]));
      px[j * 4] = px[j * 4 + 1] = px[j * 4 + 2] = v;
      px[j * 4 + 3] = 255;
    }
    encodePng(join(maskDir, `${id}-${c}.png`), hw, hh, px);
    channels.push(c);
  }
  out[id] = channels;
}
const body = Object.entries(out).map(([id, ch]) => `  '${id}': [${ch.map((c) => `'${c}'`).join(', ')}],`).join('\n');
writeFileSync(manifest, `// AUTO-GENERATED by scripts/build-part-masks.mjs — do not edit by hand.
export type MaskChannel = 'skin' | 'leather' | 'metal' | 'accent';
/** Which tint masks exist for each keyed part (public/avatar-parts/masks/<id>-<channel>.png). */
export const PART_MASKS: Record<string, readonly MaskChannel[]> = {
${body}
};
`);
